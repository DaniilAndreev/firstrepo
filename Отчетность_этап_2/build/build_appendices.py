def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        os.remove(os.path.join(OUT, f))
    paths = []
    for letter, title, intro, figs in APPS:
        d = build_protocol(letter, title) if figs is None else build_photos(letter, title, intro, figs)
        name = f"Приложение_{letter}_{title}".replace("«", "").replace("»", "").replace("/", "-")
        path = os.path.join(OUT, name[:95].rstrip() + ".docx")
        d.save(path)
        paths.append(path)
    for p in paths:
        subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", OUT, p], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=300)
        print("built", os.path.basename(p))


if __name__ == "__main__":
    main()
