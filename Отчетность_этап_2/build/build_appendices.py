def T(key):
    return apx.label(key)


class App:
    """Помощник: таблицы, рисунки и заглушки с номерами из реестра приложений."""

    def __init__(self, d):
        self.d = d
        self.done = []

    def table(self, key, title, header, rows, widths, **kw):
        self.done.append(key)
        return self.d.table(T(key), title, header, rows, widths, **kw)

    def figure(self, key, title, path, width_mm=150):
        self.done.append(key)
        return self.d.figure(T(key), title, path, width_mm)

    def photo(self, key, title, lines, ratio=0.5, width_mm=150):
        """Фото или скриншот: файл photos/<ключ>.(jpg|jpeg|png), иначе серая заглушка."""
        self.done.append(key)
        for ext in ("jpg", "jpeg", "png"):
            path = os.path.join(PHOTOS, f"{key}.{ext}")
            if os.path.exists(path):
                return self.d.figure(T(key), title, path, width_mm)
        return self.d.placeholder(T(key), title, lines, PH, key, width_mm=width_mm, ratio=ratio)


def head(d, letter, title, first=False):
    d.p(f"ПРИЛОЖЕНИЕ {letter}", align=CTR, first=False, page_break_before=not first, before=0 if not first else 12,
        keep_next=True)
    d.p(title, align=CTR, first=False, after=12, keep_next=True)


