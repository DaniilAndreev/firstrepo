def header(doc, letter, title):
    p = para(doc, f"Приложение {letter}", align=A.CENTER, bold=True, first_line=Cm(0))
    para(doc, title, align=A.CENTER, bold=True, first_line=Cm(0))
    para(doc, f"к отчёту о выполнении работ по второму этапу договора № {C['contract_no']} от "
              f"{C['contract_date']}, проект «{C['theme']}», {C['org_short']}",
         align=A.CENTER, first_line=Cm(0), after=12)


def build_app(letter, title, figs):
    doc = new_document()
    remove_leading_empty_paragraph(doc)
    # у приложений нумерация с 1 и номер на первой странице
    doc.sections[0].different_first_page_header_footer = False
    header(doc, letter, title)
    for i, (cap, lines, expl) in enumerate(figs, start=1):
        figure_placeholder(doc, f"{letter}.{i}", cap, lines, PH, width_mm=150, key=f"{letter}_{i}", height_px=950)
        para(doc, expl)
    name = f"Приложение_{letter}_{title}".replace("«", "").replace("»", "").replace("/", "-").replace(":", "")
    name = name[:90]
    path = os.path.join(OUT, name + ".docx")
    doc.save(path)
    return path


def build_protocol():
    letter, title = "Ж", "Протокол органолептической оценки образцов съедобных музыкальных пластинок"
    doc = new_document()
    remove_leading_empty_paragraph(doc)
    doc.sections[0].different_first_page_header_footer = False
    header(doc, letter, title)
    para(doc, f"Дата проведения: [УТОЧНИТЬ]. Место: [УТОЧНИТЬ]. Фокус-группа: {F.FOCUS_GROUP} человек "
              "[УТОЧНИТЬ: обозначения участников Д1–Д5]. Оценка по шкале [УТОЧНИТЬ: 1–5 баллов]; между "
              "образцами участники пили воду; состав образцов участникам не сообщался.")
    hdr = ["Образец", "Внешний вид, цвет", "Запах", "Вкус", "Сладость", "Послевкусие", "Текстура", "Средний балл", "Замечания"]
    rows = []
    samples = ["С1 сахар + глюкоза", "И0 изомальт + эритрит (Cargill)", "И0 изомальт + эритрит (STOING)",
               "I1 + патока", "I2 + мальтодекстрин", "I3 + гуммиарабик", "I4 + пектин", "I5 + какао-масло",
               "I6 «продуктовый»", "эритрит + гуммиарабик (STOING)",
               "Партия 3: «Ваниль бурбон»", "Партия 3: «Ваниль-Ром»", "Партия 3: «Апельсин сицилийский»",
               "Партия 3: «Айриш Крим»", "Партия 3: «Тутти-Фрутти»"]
    for s in samples:
        rows.append([s] + [""] * 8)
    table(doc, f"{letter}.1", "Результаты органолептической оценки (средние оценки участников)",
          hdr, rows, [34, 16, 14, 14, 16, 18, 16, 16, 21], font_size=9, header_size=9,
          align_cols=[A.LEFT] + [A.CENTER] * 7 + [A.LEFT])
    table(doc, f"{letter}.2", "Результаты проверки технических свойств образцов",
          ["Образец", "Центральное отверстие", "Плоскостность", "Липкость через 24 ч", "Влага через 7 суток", "Решение"],
          [[s, "", "", "", "", ""] for s in samples[:10]],
          [45, 28, 24, 24, 24, 20], font_size=9, header_size=9,
          align_cols=[A.LEFT] + [A.CENTER] * 5)
    para(doc, "Подписи участников фокус-группы: ______________________________________________")
    path = os.path.join(OUT, f"Приложение_{letter}_{title[:70]}.docx")
    doc.save(path)
    return path


def main():
    paths = [build_app(*a) for a in APPS]
    paths.append(build_protocol())
    for p in paths:
        subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", OUT, p],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=300)
        print("built", os.path.basename(p))


if __name__ == "__main__":
    main()
