BUILDERS = {"А": app_a, "Б": app_b, "В": app_v, "Г": app_g, "Д": app_d}


def build():
    d = dx.Doc("app", "Приложения к отчету о выполнении работ по второму этапу")
    d.p("ПРИЛОЖЕНИЯ", align=CTR, first=False)
    d.p(f"к отчету о выполнении работ по второму этапу договора о предоставлении гранта № {C['contract_no']} от "
        f"{C['contract_date']}", align=CTR, first=False)
    d.p(f"Тема: «{C['theme']}»", align=CTR, first=False)
    a = App(d)
    for i, (letter, title, objs) in enumerate(apx.APPS):
        head(d, letter, title, first=(i == 0))
        start = len(a.done)
        BUILDERS[letter](d, a)
        made = a.done[start:]
        want = [k for _, k in objs]
        if made != want:
            raise SystemExit(f"приложение {letter}: порядок объектов {made} не совпадает с реестром {want}")
    return d


def main():
    os.makedirs(OUT, exist_ok=True)
    d = build()
    d.save(DOCX)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", OUT, DOCX], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=400)
    stubs = []
    for letter, _t, objs in apx.APPS:
        for kind, key in objs:
            if key.startswith("ph_") and not any(os.path.exists(os.path.join(PHOTOS, f"{key}.{e}"))
                                                  for e in ("jpg", "jpeg", "png")):
                stubs.append(f"Рисунок {apx.label(key)}")
    print("OK", DOCX)
    print(f"заглушек под фото и скриншоты: {len(stubs)} — {', '.join(stubs)}")


if __name__ == "__main__":
    main()
