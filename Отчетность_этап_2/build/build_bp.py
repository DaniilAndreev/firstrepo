# себестоимость сырья на изделие по ценам закупки второго этапа (руб./г)
P_ISO, P_ERY, P_ACID, P_AROMA, P_DYE = 639 / 500, 421 / 1000, 290 / 300, 159 / 10, 234 / 15


def raw_cost(mass):
    parts = [mass * 0.824 * P_ISO, mass * 0.166 * P_ERY, mass * 0.006 * P_ACID, mass * 0.003 * P_AROMA,
             mass * 0.001 * P_DYE]
    return parts, sum(parts)


def make_chart(path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.ticker import FuncFormatter
    years = ["2027", "2028", "2029"]
    inc = [M.Y[y]["inc_y"] for y in (2027, 2028, 2029)]
    exp = [M.Y[y]["exp_y"] for y in (2027, 2028, 2029)]
    res = [M.Y[y]["res_y"] for y in (2027, 2028, 2029)]
    ink, ink2, grid = "#0b0b0b", "#52514e", "#e4e3df"
    fig, ax = plt.subplots(figsize=(6.3, 3.3), dpi=300)
    w, gap = 0.24, 0.015
    series = [(inc, "#2a78d6", "Доходы"), (exp, "#eb6834", "Расходы с налогом"),
              (res, "#1baf7a", "Финансовый результат")]
    for k, (vals, col, lab) in enumerate(series):
        ax.bar([i + (k - 1) * (w + gap) for i in range(3)], vals, width=w, color=col, label=lab, zorder=3)
    for i, v in enumerate(res):
        ax.annotate(fmt_num(v, 1).replace(" ", " "), (i + (w + gap), v), xytext=(0, 3),
                    textcoords="offset points", ha="center", va="bottom", fontsize=7.5, color=ink)
    ax.set_xticks(range(3))
    ax.set_xticklabels(years)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda v, p: f"{int(v):,}".replace(",", " ")))
    ax.set_ylabel("тыс. руб.", color=ink2, fontsize=8)
    ax.grid(axis="y", color=grid, linewidth=0.6, zorder=0)
    ax.set_axisbelow(True)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color("#b5b4ae")
    ax.tick_params(colors=ink2, labelsize=8, length=0)
    leg = ax.legend(loc="upper left", frameon=False, fontsize=8, ncol=3, handlelength=1.2, columnspacing=1.2)
    for t in leg.get_texts():
        t.set_color(ink)
    ax.set_ylim(0, max(inc) * 1.15)
    fig.tight_layout()
    fig.savefig(path, dpi=300, facecolor="white")
    plt.close(fig)
    return path


