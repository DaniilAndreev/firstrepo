def build(pages, keys):
    R, nf, nt = dx.make_resolver(ORDER)
    d = dx.Doc("bp", "Бизнес-план проекта «Вкусноты»", R)
    title(d)
    toc(d, pages)
    abbrev(d, keys)
    summary(d)
    sec1(d)
    sec2(d)
    sec3(d)
    sec4(d)
    sec5(d)
    sources(d)
    return d, nf, nt


def to_pdf(path):
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", os.path.dirname(path), path],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=400)
    return path[:-5] + ".pdf"


def page_map(pdf):
    with pdfplumber.open(pdf) as doc:
        texts = [(p.extract_text() or "") for p in doc.pages]
    found = {}
    for text, lvl in TOC:
        key = text[:30]
        for i, t in enumerate(texts):
            if i == 0 or t.lstrip().startswith("СОДЕРЖАНИЕ") or t.count("....") > 3:
                continue
            lines = [ln.strip() for ln in t.splitlines()]
            if any(ln == text or (len(text) > 30 and ln.startswith(key)) for ln in lines):
                found[text] = i + 1
                break
    return found, len(texts)


def used_abbr(path):
    dd = _Document(path)
    texts = [p.text for p in dd.paragraphs]
    start = next(i for i, t in enumerate(texts) if t.strip() == "ПЕРЕЧЕНЬ СОКРАЩЕНИЙ И ОБОЗНАЧЕНИЙ")
    end = next(i for i, t in enumerate(texts) if t.strip() == "РЕЗЮМЕ БИЗНЕС-ПЛАНА")
    body = "\n".join(texts[:start] + texts[end:])
    for t in dd.tables:
        for row in t.rows:
            for c in row.cells:
                body += "\n" + c.text
    return {k for k, _ in ABBR if k == "Ø" or re.search(r"(?<![\w-])" + re.escape(k) + r"(?![\w-])", body)}


def main():
    os.makedirs(OUT, exist_ok=True)
    pages, keys = {}, None
    for it in range(5):
        d, nf, nt = build(pages, keys)
        d.save(DOCX)
        if keys is None:
            keys = used_abbr(DOCX)
            continue
        pm, n = page_map(to_pdf(DOCX))
        print(f"pass {it}: pages {n}, toc {len(pm)}/{len(TOC)}")
        if pm == pages:
            break
        pages = pm
    print("figures", nf, "tables", nt, "sources", len(SOURCES), "| abbreviations:", sorted(keys))
    print("TOC missing:", [t for t, _ in TOC if t not in pages])
    print("OK", DOCX)


if __name__ == "__main__":
    main()
