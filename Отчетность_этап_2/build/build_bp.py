def make_resolver():
    nums = {}
    cf = ct = 0
    for kind, key in OBJECT_ORDER:
        if kind == "fig":
            cf += 1; nums[("fig", key)] = cf
        else:
            ct += 1; nums[("tbl", key)] = ct

    def R(text):
        def rep(m):
            kind = "fig" if m.group(1) == "F" else "tbl"
            return str(nums[(kind, m.group(2))])
        return re.sub(r"\{([FT]):([a-z0-9_]+)\}", rep, text)
    return R


# ------------------------------------------------------------------ расчётные величины (цены закупки по скриншоту корзины)
P_ISOMALT = 639 / 500      # BENEO, руб./г
P_ERYTHRITOL = 421 / 1000
P_ACID = 290 / 300
P_AROMA = 159 / 10         # Baker Flavors, 10 мл
P_DYE = 234 / 15
PACK_12 = 30 + 69 + 45     # подложка + коробка + молоточек


def unit_cost(mass):
    iso = mass * 0.824 * P_ISOMALT
    ery = mass * 0.166 * P_ERYTHRITOL
    acid = mass * 0.006 * P_ACID
    aroma = mass * 0.003 * P_AROMA
    dye = mass * 0.001 * P_DYE
    return iso, ery, acid, aroma, dye, iso + ery + acid + aroma + dye


