def to_pdf(path):
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", os.path.dirname(path), path],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=400)
    return path[:-5] + ".pdf"


def page_map(pdf):
    with pdfplumber.open(pdf) as doc:
        texts = [(p.extract_text() or "") for p in doc.pages]
    found = {}
    for text, lvl in TOC:
        key = text if len(text) < 40 else text[:34]
        for i, t in enumerate(texts):
            if t.lstrip().startswith("СОДЕРЖАНИЕ") or t.count("....") > 3:
                continue
            lines = [ln.strip() for ln in t.splitlines()]
            if any(ln == text or (len(text) >= 40 and ln.startswith(key)) for ln in lines):
                found[text] = i + 2
                break
    return found, len(texts)


def used_abbr(docx_path):
    dd = _Document(docx_path)
    texts = [p.text for p in dd.paragraphs]
    start = next(i for i, t in enumerate(texts) if t.strip() == "ПЕРЕЧЕНЬ СОКРАЩЕНИЙ И ОБОЗНАЧЕНИЙ")
    end = next(i for i, t in enumerate(texts) if t.strip() == "ВВЕДЕНИЕ" and i > start)
    body = "\n".join(texts[:start] + texts[end:])
    for t in dd.tables:
        for row in t.rows:
            for c in row.cells:
                body += "\n" + c.text
    keys = set()
    for k, _ in ABBR:
        if k == "Ø" or re.search(r"(?<![\w-])" + re.escape(k) + r"(?![\w-])", body):
            keys.add(k)
    return keys


def main():
    os.makedirs(OUT, exist_ok=True)
    pages, cnt, keys = {}, ("0", "0", "0"), None
    for it in range(5):
        d, nf, nt = build(pages, cnt, keys)
        d.save(DOCX)
        if keys is None:
            keys = used_abbr(DOCX)
            continue
        pdf = to_pdf(DOCX)
        pm, n = page_map(pdf)
        new_cnt = (str(n + 1), str(nf), str(nt))
        print(f"pass {it}: pdf pages {n}, printed last page {n + 1}, toc {pm}")
        if pm == pages and new_cnt == cnt:
            break
        pages, cnt = pm, new_cnt
    missing = [t for t, _ in TOC if t not in pages]
    print("figures", nf, "tables", nt, "sources", len(SOURCES), "| abbreviations:", sorted(keys))
    print("TOC missing:", missing)
    print("OK", DOCX)


