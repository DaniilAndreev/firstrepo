def build(pages, cnt, abbr_keys):
    R0, nf, nt = dx.make_resolver(ORDER)
    d = dx.Doc("report", "Отчет о выполнении работ по второму этапу", lambda t: R0(apx.resolve(t)))
    referat(d, cnt)
    toc(d, pages)
    abbrev(d, abbr_keys)
    intro(d)
    d.h1(MAIN)
    for sec in (s11, s12, s13, s14, s15):
        sec(d)
    conclusion(d)
    sources(d)
    return d, nf, nt


def to_pdf(path):
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", os.path.dirname(path), path],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=400)
    return path[:-5] + ".pdf"


def _norm(t):
    return " ".join(t.replace(" ", " ").split())


def page_map(pdf):
    with pdfplumber.open(pdf) as doc:
        texts = [(p.extract_text() or "") for p in doc.pages]
    found = {}
    for text, lvl in TOC:
        key = _norm(text)[:38]
        for i, t in enumerate(texts):
            if t.lstrip().startswith("СОДЕРЖАНИЕ") or t.count("....") > 3:
                continue
            lines = [_norm(ln) for ln in t.splitlines()]
            if any(ln == _norm(text) or (len(key) >= 38 and ln.startswith(key)) for ln in lines):
                found[text] = i + 2
                break
    return found, len(texts)


def used_abbr(docx_path):
    dd = _Document(docx_path)
    texts = [p.text for p in dd.paragraphs]
    start = next(i for i, t in enumerate(texts) if t.strip() == "ПЕРЕЧЕНЬ СОКРАЩЕНИЙ И ОБОЗНАЧЕНИЙ")
    end = next(i for i, t in enumerate(texts) if t.strip() == "ВВЕДЕНИЕ" and i > start)
    body = "\n".join(texts[:start] + texts[end:])
    for t in dd.tables:
        for row in t.rows:
            for c in row.cells:
                body += "\n" + c.text
    keys = set()
    for k, _ in ABBR:
        if k == "Ø" or re.search(r"(?<![\w-])" + re.escape(k) + r"(?![\w])", body):
            keys.add(k)
    return keys


