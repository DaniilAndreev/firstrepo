def build():
    d = dx.Doc("dev", "Отчет о развитии проекта «Вкусноты»", lambda s: s)
    d.h1("Отчет о развитии проекта", page_break=False)
    rows = [["Выполненные мероприятия"]]
    rows += [[str(i + 1), a, b, c] for i, (a, b, c) in enumerate(DONE)]
    rows.append(["Планируемые мероприятия"])
    sep = len(rows) - 1
    rows += [[str(i + 1), a, b, c] for i, (a, b, c) in enumerate(PLANNED)]
    d.table("1", "Отчет о развитии проекта", ["№ п/п", "Наименование мероприятия", "Да/Нет", "Комментарий"],
            rows, [12.3, 50.3, 33.5, 68.9], size=12, align_cols=[A.CENTER, A.LEFT, A.CENTER, A.LEFT],
            merge_rows=[0, sep], keep_together=False, cant_split=False, caption=False)
    return d


def main():
    os.makedirs(OUT, exist_ok=True)
    build().save(DOCX)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", OUT, DOCX], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=300)
    print("OK", DOCX)


if __name__ == "__main__":
    main()
