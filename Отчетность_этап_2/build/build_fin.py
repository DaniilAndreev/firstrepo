def money(s):
    return D(s.replace(" ", "").replace(" ", "").replace(",", ".") or "0")


def rub(x):
    return x.quantize(D("1"), ROUND_HALF_UP)


def fm(x, dec=2):
    q = D(1).scaleb(-dec) if dec else D(1)
    x = D(x).quantize(q, ROUND_HALF_UP)
    neg = x < 0
    s = f"{abs(x):,.{dec}f}".replace(",", "X").replace(".", ",").replace("X", NBSP)
    return ("−" if neg else "") + s


# ------------------------------------------------------------------ выписка
def load(folder):
    ops = []
    for path in sorted(glob.glob(os.path.join(folder, "*.csv"))):
        with open(path, encoding="utf-8-sig", newline="") as f:
            for r in csv.DictReader(f, delimiter=";"):
                out = r["Направление"].startswith("Исх")
                ops.append(dict(
                    date=r["Дата проводки"], doc_date=r["Дата документа"], num=r["Номер документа"],
                    out=out, amount=money(r["Сумма операции"]), purpose=r["Назначение платежа"],
                    cp=(r["Наименование получателя"] if out else r["Наименование плательщика"]),
                    cp_inn=(r["ИНН получателя"] if out else r["ИНН плательщика"]),
                    kbk=r.get("Бюджетный: КБК", ""), balance=money(r["Исходящий остаток"]),
                    raw=r))
    ops.sort(key=lambda o: (o["date"][6:], o["date"][3:5], o["date"][:2]))
    return ops


def card_date(op):
    m = re.search(r"дата операции:(\d\d)/(\d\d)/(\d{4})", op["purpose"])
    return f"{m.group(1)}.{m.group(2)}.{m.group(3)}" if m else op["date"]


def classify(op):
    p, cp = op["purpose"], op["cp"].upper()
    if not op["out"]:
        if "уставн" in p.lower():
            return "in_charter"
        if "Безвозмездная" in p:
            return "in_aid"
        if op["kbk"].endswith("610"):
            return "in_ens_refund"
        if p.startswith("Возврат товара"):
            return "in_card_refund"
        return "in_other"
    if "Заработная плата" in p or "Аванс по трудовому договору" in p:
        return "salary"
    if "Зарплатному проекту" in p:
        return "fee_salary"
    if op["kbk"] == "18201061201010000510":
        return "enp"
    if "лицензионного вознаграждения" in p:
        return "fee_tariff"
    if "программе лояльности" in p:
        return "loyalty"
    if "Покупка товара" in p:
        term = re.search(r"Терминал:([^,]+)", p).group(1)
        if term.startswith("OB*OZON"):
            return "card_ozon_misc"
        if "OZON" in term:
            return "card_ozon"
        if "TORTOMASTER" in term:
            return "card_tortomaster"
        if "DIRECT" in term:
            return "card_direct"
        if "beget" in term.lower():
            return "card_beget"
        if "master-stampov" in term:
            return "card_seal"
        return "card_other"
    if "ПАРАТАЙП" in cp:
        return "paratype"
    if "МАЛИСЕВИЧ" in cp:
        return "outdoor"
    return "other"


def analyse(ops):
    for o in ops:
        o["kind"] = classify(o)
        o["returned"] = False
    # возврат положительного сальдо ЕНС: какие платежи ЕНП вернулись
    enp = [o for o in ops if o["kind"] == "enp"]
    for ref in [o for o in ops if o["kind"] == "in_ens_refund"]:
        for k in range(1, len(enp) + 1):
            hit = next((c for c in combinations(enp, k) if sum(x["amount"] for x in c) == ref["amount"]), None)
            if hit:
                for x in hit:
                    x["returned"] = ref
                break
    # возврат товара по карте
    for ref in [o for o in ops if o["kind"] == "in_card_refund"]:
        for o in ops:
            if o["kind"].startswith("card_") and o["amount"] == ref["amount"] and not o["returned"]:
                o["returned"] = ref
                break
    return ops


# ------------------------------------------------------------------ зарплата и НДФЛ
def salary_month(op):
    m = re.search(r"за (" + "|".join(MONTHS) + r") (\d{4})", op["purpose"])
    pay_m, pay_y = int(op["date"][3:5]), int(op["date"][6:])
    if m:
        mon, year = MONTHS.index(m.group(1)) + 1, int(m.group(2))
        if (year, mon) < (2025, 11):  # раньше регистрации ООО (01.11.2025) — ошибка в назначении
            return (pay_y, pay_m), f"в назначении ошибочно «за {m.group(1)} {m.group(2)}»"
        return (year, mon), ""
    return (pay_y, pay_m), ""


def register(op):
    m = re.search(r"реестру зачислений № (\d+)", op["purpose"])
    return m.group(1) if m else "[УТОЧНИТЬ]"


def due_status(op):
    d, m, y = int(op["date"][:2]), int(op["date"][3:5]), int(op["date"][6:])
    if (y, m) == (2026, 10) and d <= 22:
        return "срок не наступил (до 28.10.2026)"
    return "просрочен"


def ndfl_rows(ops):
    rows = []
    paid = [o for o in ops if o["kind"] == "enp" and not o["returned"]]
    paid_left = {o["date"]: o["amount"] for o in paid}
    for o in [o for o in ops if o["kind"] == "salary"]:
        tax = rub(o["amount"] * 13 / 87)
        (y, mth), flag = salary_month(o)
        covered = D(0)
        if o["date"] in paid_left:  # ЕНП в день выплаты — засчитываем в эту выплату
            covered = min(paid_left.pop(o["date"]), tax)
        rows.append(dict(op=o, tax=tax, covered=covered, unpaid=tax - covered, month=(y, mth), flag=flag,
                         gross_tax=rub(o["amount"] * D("0.13"))))
    return rows, paid


