def make_resolver():
    nums = {}
    cf = ct = 0
    for kind, key in OBJECT_ORDER:
        if kind == "fig":
            cf += 1
            nums[("fig", key)] = cf
        else:
            ct += 1
            nums[("tbl", key)] = ct

    def R(text):
        import re
        def rep(m):
            kind = "fig" if m.group(1) == "F" else "tbl"
            return str(nums[(kind, m.group(2))])
        return re.sub(r"\{([FT]):([a-z0-9_]+)\}", rep, text)

    def N(kind, key):
        return nums[(kind, key)]

    return R, N, cf, ct


